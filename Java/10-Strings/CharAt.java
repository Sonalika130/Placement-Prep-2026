//space also an character
public class CharAt {
    public static void main(String[] args){
        //extracting each characters
        String st="hello hi";
        for(int i=0;i<st.length();i++){
            System.out.println(st.charAt(i));
        }

    
    System.out.println(st.charAt(0));
    System.out.println(st.charAt(4));
    
}
}
